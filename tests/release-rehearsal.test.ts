import test from "node:test";
import assert from "node:assert/strict";
import Database from "better-sqlite3";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

test("offline release rehearsal reads live WAL, preserves source, verifies files and fails closed", t => {
  const root = mkdtempSync(path.join(tmpdir(), "blabla-release-test-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const source = path.join(root, "source.db"), db = new Database(source);
  t.after(() => db.close());
  db.pragma("journal_mode=WAL"); db.pragma("wal_autocheckpoint=0");
  db.exec(`CREATE TABLE forum_watches(user_id TEXT,topic_id TEXT); CREATE TABLE forum_topics(id TEXT PRIMARY KEY);
    CREATE TABLE documents(id TEXT PRIMARY KEY,file_url TEXT); CREATE TABLE seminars(id TEXT PRIMARY KEY);
    CREATE TABLE forum_posts(id TEXT PRIMARY KEY); CREATE TABLE annotations(id TEXT PRIMARY KEY);
    CREATE TABLE users(id TEXT PRIMARY KEY,email TEXT); CREATE TABLE channels(id TEXT PRIMARY KEY);
    CREATE TABLE channel_posts(id TEXT PRIMARY KEY,channel_id TEXT,author_id TEXT,body TEXT);
    CREATE TABLE channel_comments(id TEXT PRIMARY KEY); CREATE TABLE channel_moderators(channel_id TEXT,user_id TEXT);
    CREATE TABLE site_settings(key TEXT PRIMARY KEY,value TEXT);
    INSERT INTO users VALUES('reader','reader@example.test'); INSERT INTO channels VALUES('channel');
    INSERT INTO channel_posts VALUES('post','channel','reader','Existing writing');
    INSERT INTO documents VALUES('book','/uploads/book.txt');
    INSERT INTO site_settings VALUES('feature_flags','{"modes":{"channels":"off"}}');`);
  const uploads = path.join(root, "public/uploads"); mkdirSync(uploads, { recursive: true });
  writeFileSync(path.join(uploads, "book.txt"), "Original library text");
  const run = (bootstrap = false) => {
    const result = spawnSync(process.execPath, ["--import", "tsx", "scripts/verify-release.ts", source, root, root, ...(bootstrap ? ["--bootstrap"] : [])], { encoding: "utf8" });
    assert.equal(result.signal, null); assert(result.stdout.trim(), result.stderr);
    const output = JSON.parse(result.stdout.trim());
    return { result, report: JSON.parse(readFileSync(output.report, "utf8")) };
  };
  const ok = run(); assert.equal(ok.result.status, 0, ok.result.stderr); assert.equal(ok.report.ready, true);
  assert.equal(ok.report.productionVerified, false); assert.equal(ok.report.applied.length, 3);
  assert.equal(ok.report.files[0].status, "ok"); assert.equal(ok.report.files[0].size, 21);
  assert.equal(db.prepare("SELECT name FROM sqlite_master WHERE name='schema_migrations'").get(), undefined);
  assert.equal((db.prepare("SELECT body FROM channel_posts").get() as { body: string }).body, "Existing writing");
  assert.equal(ok.report.before.find((table: { name: string }) => table.name === "users").count, 1);
  const runtimeChange = run(true);
  assert.equal(runtimeChange.result.status, 1); assert.equal(runtimeChange.report.ready, false);
  assert.match(runtimeChange.report.error, /Runtime bootstrap changed/);
  assert.equal(runtimeChange.report.bootstrap.unchanged, false);
  assert.equal(db.prepare("SELECT name FROM pragma_table_info('users') WHERE name='avatar_key'").get(), undefined, "bootstrap must never reach the source");
  rmSync(path.join(uploads, "book.txt"));
  const failed = run(); assert.equal(failed.result.status, 1); assert.equal(failed.report.ready, false);
  assert.equal(failed.report.contentPreserved, true); assert.equal(failed.report.files[0].status, "missing-or-external-symlink");
  const refused = spawnSync("bash", ["deploy/release.sh"], { encoding: "utf8" });
  assert.equal(refused.status, 2); assert.match(refused.stderr, /Automatic deployment is disabled/);
});
